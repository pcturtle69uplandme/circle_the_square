"""
Circle the Square — Qwen3-TTS Synthesis Script

Two-phase pipeline, per character:
  1. REFERENCE — the character's first line is synthesized once via VoiceDesign
     (instruct/text-controlled accent, from CARTOON_CAST_BIBLE.md).
  2. CLONE — every other line for that character is generated by cloning the
     reference take's exact voice identity (Qwen3-TTS "Base" model,
     generate_voice_clone), NOT by calling VoiceDesign again per line.

Why: VoiceDesign samples a brand-new voice from the text description on
every single call — same instruct, different random voice each time. That
is what caused different mp3s for the same character to sound like
different people (found 2026-08-28, Christina/Jan). Cloning from one
approved reference line keeps the whole character consistent. Named
CustomVoice presets (Ryan/Serena/Vivian/Dylan/Uncle_Fu) were tried first and
dropped entirely: they're fixed voices but don't reliably land a specified
accent (e.g. "Serena" read Asian-accented instead of British RP).

Both phases reject and retry any take whose pitch (F0) is flat/monotone —
that pattern (e.g. a 6 Hz range dead-flat take) is a real TTS failure mode,
not just "different-sounding", and previously produced Christina's F01
"male robot" line.

Outputs to: C:\\AI\\Circle the Square\\docs\\audio-refs\\
Naming:  {character}_{index}.mp3  e.g. jan_01.mp3, christina_01.mp3
That folder — not a sibling audio-refs/ at the repo root — is the actual
document root the bubble studio's HTTP server (docs/) serves from; a
repo-root copy is never reachable by the page's "../audio-refs/..." URLs
(found 2026-08-28 after regenerating the wrong folder for an hour).
"""

