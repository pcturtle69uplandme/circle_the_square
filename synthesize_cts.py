# ── Main ──────────────────────────────────────────────────────────────────────
_ensure_qwen_package()
ModelClass = _load_qwen3_model()
if ModelClass is None:
    print("ERROR: Could not load Qwen3-TTS model. Check AILab_QwenTTS installation.")
    sys.exit(1)

total_generated = 0
total_skipped = 0
total_failed = 0

# ── Phase 1: reference line per character (VoiceDesign) ─────────────────────
print(f"\n{'='*60}\nPHASE 1 — reference lines (VoiceDesign)\n{'='*60}")
vd_model_dir = COMFY_ROOT / "models" / "TTS" / "Qwen3-TTS" / "Qwen3-TTS-12Hz-1.7B-VoiceDesign"
vd_model = None

for character, cfg in CHARACTERS.items():
    ref_path = OUT_DIR / f"{character}_01.mp3"
    if ref_path.exists():
        print(f"[{character}] [SKIP] {ref_path.name} (already exists)")
        total_skipped += 1
        continue
    if 1 in cfg["pinned"]:
        print(f"[{character}] [SKIP] {ref_path.name} (pinned, hand-authored)")
        continue
    if vd_model is None:
        print(f"Loading VoiceDesign model from {vd_model_dir} ...")
        vd_model = ModelClass.from_pretrained(
            str(vd_model_dir),
            dtype=torch.float16 if torch.cuda.is_available() else torch.float32,
            device_map="cuda" if torch.cuda.is_available() else "cpu",
        )
    print(f"[{character}] generating reference {ref_path.name}")
    ok = generate_reference(vd_model, cfg["instruct"], cfg["lines"][0], ref_path)
    if ok:
        total_generated += 1
    else:
        total_failed += 1

if vd_model is not None:
    del vd_model
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

# ── Phase 2: clone every other line from the reference ───────────────────────
print(f"\n{'='*60}\nPHASE 2 — clone remaining lines (Base / generate_voice_clone)\n{'='*60}")
base_model_dir = COMFY_ROOT / "models" / "TTS" / "Qwen3-TTS" / "Qwen3-TTS-12Hz-1.7B-Base"
base_model = None

for character, cfg in CHARACTERS.items():
    lines = cfg["lines"]
    pinned = cfg["pinned"]
    ref_path = OUT_DIR / f"{character}_01.mp3"

    # Which of this character's other lines actually need generating?
    todo = [
        (i, text) for i, text in enumerate(lines[1:], start=2)
        if i not in pinned and not (OUT_DIR / f"{character}_{i:02d}.mp3").exists()
    ]
    if not todo:
        continue
    if not ref_path.exists():
        print(f"[{character}] SKIPPING {len(todo)} line(s) -- no reference {ref_path.name} to clone from")
        total_failed += len(todo)
        continue

    if base_model is None:
        print(f"Loading Base (voice-clone) model from {base_model_dir} ...")
        base_model = ModelClass.from_pretrained(
            str(base_model_dir),
            dtype=torch.float16 if torch.cuda.is_available() else torch.float32,
            device_map="cuda" if torch.cuda.is_available() else "cpu",
        )

    print(f"\n[{character}] building voice-clone prompt from {ref_path.name}")
    prompt_items = base_model.create_voice_clone_prompt(
        ref_audio=str(ref_path),
        ref_text=lines[0],
        x_vector_only_mode=False,
    )

    for i, text in todo:
        out_path = OUT_DIR / f"{character}_{i:02d}.mp3"
        print(f"  [{character}_{i:02d}]")
        ok = generate_clone(base_model, prompt_items, text, out_path)
        if ok:
            total_generated += 1
        else:
            total_failed += 1

if base_model is not None:
    del base_model
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

print(f"\n{'='*60}")
print(f"Done. {total_generated} generated, {total_skipped} skipped (already existed), {total_failed} failed.")
print(f"  Output: {OUT_DIR}")
