# ── Quality gate ───────────────────────────────────────────────────────────────
MIN_PITCH_RANGE_HZ = 15.0  # below this, a take reads as flat/monotone -- reject and retry
MAX_RETRIES = 4

def measure_pitch(path: Path):
    """Mean F0 and pitch range (Hz) of a wav/mp3. Returns (None, None) if unvoiced/silent."""
    y, sr = librosa.load(str(path), sr=None)
    f0, voiced_flag, voiced_prob = librosa.pyin(
        y, fmin=librosa.note_to_hz("C2"), fmax=librosa.note_to_hz("C7"), sr=sr
    )
    valid = f0[~np.isnan(f0)]
    if len(valid) == 0:
        return None, None
    return float(np.mean(valid)), float(np.max(valid) - np.min(valid))


def wav_to_mp3(wav_path: Path, mp3_path: Path, bitrate: str = "128k"):
    from pydub import AudioSegment
    AudioSegment.from_wav(str(wav_path)).export(str(mp3_path), format="mp3", bitrate=bitrate)
    wav_path.unlink(missing_ok=True)


def generate_reference(model, instruct: str, text: str, out_path: Path) -> bool:
    """VoiceDesign, quality-gated with retries. Returns True on success."""
    wav_path = out_path.with_suffix(".wav")
    for attempt in range(1, MAX_RETRIES + 1):
        print(f"    attempt {attempt}: '{text[:50]}'")
        wavs, sr = model.generate_voice_design(text=text, instruct=instruct, language="english")
        sf.write(str(wav_path), wavs[0], sr)
        mean_f0, rng = measure_pitch(wav_path)
        if mean_f0 is None:
            print("      no pitch detected -- retrying")
            continue
        print(f"      mean F0={mean_f0:.1f} Hz, range={rng:.1f} Hz")
        if rng >= MIN_PITCH_RANGE_HZ:
            wav_to_mp3(wav_path, out_path)
            print(f"      ACCEPTED -> {out_path.name} ({out_path.stat().st_size/1024:.1f} KB)")
            return True
        print("      REJECTED (flat/monotone) -- retrying")
    print(f"    FAILED after {MAX_RETRIES} attempts")
    return False


def generate_clone(model, voice_clone_prompt, text: str, out_path: Path) -> bool:
    """Voice-clone from a prebuilt prompt, quality-gated with retries. Returns True on success."""
    wav_path = out_path.with_suffix(".wav")
    for attempt in range(1, MAX_RETRIES + 1):
        print(f"    attempt {attempt}: '{text[:50]}'")
        wavs, sr = model.generate_voice_clone(text=text, language="english", voice_clone_prompt=voice_clone_prompt)
        sf.write(str(wav_path), wavs[0], sr)
        mean_f0, rng = measure_pitch(wav_path)
        if mean_f0 is None:
            print("      no pitch detected -- retrying")
            continue
        print(f"      mean F0={mean_f0:.1f} Hz, range={rng:.1f} Hz")
        if rng >= MIN_PITCH_RANGE_HZ:
            wav_to_mp3(wav_path, out_path)
            print(f"      ACCEPTED -> {out_path.name} ({out_path.stat().st_size/1024:.1f} KB)")
            return True
        print("      REJECTED (flat/monotone) -- retrying")
    print(f"    FAILED after {MAX_RETRIES} attempts")
    return False


